import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
const caillebotte = "95e6574a-8509-4c70-ad3b-d22ed2cc1e83", monet = "cb33c32e-16ea-4d3e-9da0-287f5686585b";

test("owner publishes and revokes; anonymous readers can inspect and compare without editing", async ({ page, browser, baseURL }, info) => {
  test.setTimeout(120000);
  expect((await (await page.request.get("/api/auth/session")).json()).local_debug).toBe(true);
  const headers = { Origin: baseURL! };
  const created = await page.request.post("/api/studies", { data: { title: "Paris — shared research" }, headers });
  expect(created.ok()).toBe(true);
  const study = await created.json(); expect(study.public).toBe(false);
  expect((await page.request.get(`/api/shared-studies/${study.id}`)).status()).toBe(404);
  for (const data of [{ refs: [{ kind: "artwork", id: caillebotte }, { kind: "artwork", id: monet }] }, { link: { kind: "book", title: "L’Assommoir — first book edition", creator: "Émile Zola", year: 1877 } }]) expect((await page.request.post(`/api/studies/${study.id}/records`, { headers, data })).ok()).toBe(true);
  expect((await page.request.put(`/api/studies/${study.id}/records/artwork/${caillebotte}`, { headers, data: { note: "Compare the public street and railway.\n<script>Literal research text</script>" } })).ok()).toBe(true);
  await page.goto(`/studies/${study.id}`);
  await page.getByRole("button", { name: "Share", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Share study", exact: true });
  await expect(dialog.getByRole("heading", { name: "Private", exact: true })).toBeVisible();
  await expect(dialog).toContainText("research notes");
  await dialog.getByRole("button", { name: "Enable public link", exact: true }).click();
  await expect(dialog.getByLabel("Public link", { exact: true })).toBeVisible();
  const link = await dialog.getByLabel("Public link", { exact: true }).inputValue(), token = new URL(link).pathname.split("/").at(-1)!;
  expect(token).not.toBe(study.id);
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: info.outputPath(`share-dialog-${width}.png`) });
  }
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  const visitor = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
  await visitor.route("**/api/auth/session", route => route.fulfill({ json: { enabled: true, user: null } }));
  const reader = await visitor.newPage(), errors: string[] = []; reader.on("pageerror", error => errors.push(error.message));
  await reader.goto(link);
  await expect(reader.getByRole("heading", { name: "Paris — shared research", exact: true })).toBeVisible();
  await expect(reader.getByText("Public study · Read only", { exact: true })).toBeVisible();
  for (const name of ["+ Add records", "Study settings", "Share"]) await expect(reader.getByRole("button", { name, exact: true })).toHaveCount(0);
  await expect(reader.getByText("Export", { exact: true })).toHaveCount(0);
  await reader.getByRole("button", { name: /^Paris Street; Rainy Day/ }).click();
  await expect(reader.getByRole("heading", { name: "Research note", exact: true })).toBeVisible();
  await expect(reader.getByRole("region", { name: "Record inspection", exact: true })).toContainText("<script>Literal research text</script>");
  await expect(reader.getByRole("textbox", { name: "Your note", exact: true })).toHaveCount(0);
  await expect(reader.getByRole("button", { name: "Remove from study", exact: true })).toHaveCount(0);
  await reader.screenshot({ path: info.outputPath("public-timeline-1440.png") });
  expect((await new AxeBuilder({ page: reader }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await reader.getByRole("button", { name: "Compare artworks", exact: true }).click();
  await expect(reader.getByRole("dialog", { name: "Compare artworks", exact: true }).getByRole("heading", { name: "Paris Street; Rainy Day", exact: true })).toBeVisible();
  await reader.keyboard.press("Escape");
  await reader.getByRole("button", { name: "Close record", exact: true }).click();
  await reader.getByRole("searchbox", { name: "Search this study" }).fill("first book edition");
  await expect(reader.getByRole("status").filter({ hasText: "1 of 3 records" })).toBeVisible();
  await reader.getByRole("button", { name: "Reset filters", exact: true }).first().click();
  for (const width of [390, 320]) {
    await reader.setViewportSize({ width, height: 900 }); await reader.goto(link + "?view=gallery");
    await expect(reader.getByRole("status").filter({ hasText: "3 of 3 records" })).toBeVisible();
    expect(await reader.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await reader.screenshot({ path: info.outputPath(`public-gallery-${width}.png`) });
    await reader.getByRole("button", { name: /Artwork Paris Street; Rainy Day/ }).click();
    await expect(reader.getByRole("dialog", { name: "Record inspection", exact: true }).getByRole("heading", { name: "Research note", exact: true })).toBeVisible();
    expect((await new AxeBuilder({ page: reader }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
    await reader.screenshot({ path: info.outputPath(`public-inspector-${width}.png`) }); await reader.keyboard.press("Escape");
  }
  for (const method of ["POST", "PUT", "PATCH", "DELETE"]) expect((await visitor.request.fetch(`/api/shared-studies/${token}`, { method, data: { title: "changed" } })).status()).toBe(405);
  const response = await visitor.request.get(`/api/shared-studies/${token}`);
  expect(response.headers()["cache-control"]).toBe("private, no-store"); expect((await response.json()).share_token).toBeUndefined();
  await page.getByRole("button", { name: "Share", exact: true }).click();
  await dialog.getByRole("button", { name: "Make private", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "Private", exact: true })).toBeVisible();
  expect((await visitor.request.get(`/api/shared-studies/${token}`)).status()).toBe(404);
  await reader.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(reader.getByRole("heading", { name: "Study unavailable", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Enable public link", exact: true }).click();
  await expect(dialog.getByLabel("Public link", { exact: true })).toBeVisible();
  expect(await dialog.getByLabel("Public link", { exact: true }).inputValue()).not.toBe(link);
  expect((await visitor.request.get(`/api/shared-studies/${token}`)).status()).toBe(404);
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByRole("button", { name: "Share", exact: true })).toBeFocused();
  await page.goto("/studies"); await expect(page.getByRole("link", { name: /Paris — shared research/ }).first()).toContainText("Public");
  expect(errors).toEqual([]); await visitor.close();
});
